"""奇遇事件池（100+ 事件）
数据格式：E(title, desc, [(label, weight, win, lose), ...])
  weight: risk(高收益高风险) / safe(稳) / good(善行) / evil(恶行) / leave(离开)
  win/lose 为 dict，可含 gold / exp / hp_pct / karma / luck / item
  奖励数值为基础值，运行时按玩家境界缩放。
"""


def E(title, desc, options, min_level=0):
    return {
        "key": title,
        "title": title,
        "desc": desc,
        "min_level": min_level,
        "options": [
            {"label": o[0], "weight": o[1], "win": o[2] or None, "lose": o[3] or None}
            for o in options
        ],
    }


def _g(gold=0, exp=0, hp=0, karma=0, luck=0, item=None, count=1):
    d = {}
    if gold: d["gold"] = gold
    if exp: d["exp"] = exp
    if hp: d["hp_pct"] = hp
    if karma: d["karma"] = karma
    if luck: d["luck"] = luck
    if item: d["item"] = {"name": item, "count": count}
    return d


